#!/usr/bin/env bash
# TreeGround environment on CINECA Leonardo. Run on a LOGIN node (needs internet).
#   scripts/cineca_setup.sh [base_dir [data_base]]
# base_dir  (default $WORK/treeground): venv, HF weights, pip/torch caches, runs (irreplaceable)
# data_base (default base_dir): datasets + feature caches (bulk, regenerable; $SCRATCH is fine)
# Knobs: TG_ACCOUNT (AIFAC_S07_041), TG_PYTHON (python3), CUDA_WHEELS (cu126), MIN_FREE_GB (200)
set -euo pipefail

REPO=$(cd "$(dirname "$0")/.." && pwd)
ACCOUNT=${TG_ACCOUNT:-AIFAC_S07_041}
PY=${TG_PYTHON:-python3}
CUDA_WHEELS=${CUDA_WHEELS:-cu126}
MIN_FREE_GB=${MIN_FREE_GB:-200}

free_gb() { df -Pk "$1" 2>/dev/null | awk 'NR==2 {print int($4/1024/1024)}'; }
outside_home() {
    case "$1" in "$HOME"|"$HOME"/*) echo "ERROR: $2 $1 is inside \$HOME (small quota) - refusing" >&2; exit 1;; esac
}

BASE=${1:-${TG_BASE:-}}
if [ -z "$BASE" ]; then
    [ -n "${WORK:-}" ] && [ -d "$WORK" ] || { echo "ERROR: \$WORK not set; pass base_dir" >&2; exit 1; }
    BASE="$WORK/treeground"
fi
mkdir -p "$BASE"
BASE=$(readlink -f "$BASE")
DATA_BASE=${2:-${TG_DATA_BASE:-$BASE}}
mkdir -p "$DATA_BASE"
DATA_BASE=$(readlink -f "$DATA_BASE")
outside_home "$BASE" "base dir"
outside_home "$DATA_BASE" "data base"
case "$REPO" in "$HOME"|"$HOME"/*) echo "WARNING: repo checkout $REPO is inside \$HOME; clone it under \$WORK";; esac
if [ -n "${SCRATCH:-}" ]; then
    case "$DATA_BASE" in "$SCRATCH"*) echo "NOTE: data on \$SCRATCH (purged periodically); datasets/caches are regenerable";; esac
    case "$BASE" in "$SCRATCH"*) echo "WARNING: base on \$SCRATCH: runs and checkpoints may be purged";; esac
fi
[ "$(free_gb "$DATA_BASE")" -ge "$MIN_FREE_GB" ] || {
    echo "ERROR: $DATA_BASE has $(free_gb "$DATA_BASE") GB free, need >= $MIN_FREE_GB (COCO ~33 GB + caches)" >&2; exit 1; }

"$PY" -c 'import sys; assert sys.version_info >= (3, 11), sys.version' 2>/dev/null || {
    echo "ERROR: $PY is $("$PY" -V 2>&1); need >= 3.11. Load one first, e.g.:" >&2
    echo "       module avail python   then   module load <python 3.11+ module>   (or set TG_PYTHON)" >&2
    exit 1; }

mkdir -p "$BASE"/{hf,xdg,torch,triton,runs} "$DATA_BASE"/{data,cache} "$REPO/logs"
ENV_FILE="$BASE/tg_env.sh"
cat > "$ENV_FILE" <<EOF
# Generated by scripts/cineca_setup.sh - source in every shell and job.
export TG_REPO="$REPO"
export TG_ROOT="$BASE"
export TG_DATA="$DATA_BASE/data"
export TG_CACHE="$DATA_BASE/cache"
export TG_RUNS="$BASE/runs"
export TG_VENV="$BASE/tg-venv"
export TG_SLURM_ACCOUNT="$ACCOUNT"
export HF_HOME="$BASE/hf"
export XDG_CACHE_HOME="$BASE/xdg"
export PIP_CACHE_DIR="$BASE/xdg/pip"
export TORCH_HOME="$BASE/torch"
export TRITON_CACHE_DIR="$BASE/triton"
if [ -f "\$TG_VENV/bin/activate" ]; then
    source "\$TG_VENV/bin/activate"
    source "\$TG_REPO/slurm/env.sh"
fi
EOF
echo "Wrote $ENV_FILE"

if [ ! -f "$BASE/tg-venv/bin/activate" ]; then
    "$PY" -m venv "$BASE/tg-venv"
fi
# shellcheck disable=SC1090
source "$ENV_FILE"
source "$BASE/tg-venv/bin/activate"
python -m pip install --quiet --upgrade pip
pip install --quiet "torch==2.14.1" "torchvision==0.29.1" --index-url "https://download.pytorch.org/whl/$CUDA_WHEELS"
pip install --quiet -e "$REPO[dev]" "zstandard==0.25.0"
source "$ENV_FILE"
echo "venv ready: $(python -V) torch $(python -c 'import torch; print(torch.__version__)')"

python "$REPO/scripts/verify_env.py" --skip-models --skip-data
echo
echo "Next (login node):  source $ENV_FILE"
echo "  hf auth login                      # needs approved access to facebook/sam3"
echo "  python scripts/fetch_models.py"
echo "  bash scripts/fetch_data.sh"
echo "  python scripts/verify_env.py"
